// Shapes returned by the FastAPI backend (see demo/backend/schemas.py).

export interface ApplicationResponse {
  action: string;
  model_decision: string;
  route_to: string | null;
  offers: string[];
  suggested_intent: string | null;
}

export type DecisionStatus = "accepted" | "fallback_applied";

export interface Decision {
  raw_prediction: string;
  confidence: number;
  threshold: number;
  final_intent: string;
  status: DecisionStatus;
  below_threshold: boolean;
  fallback_applied: boolean;
  application: ApplicationResponse;
}

export interface Contribution {
  feature: string;
  count: number;
  weight: number;
  contribution: number;
  contribution_vs_runner_up: number;
}

export interface Explanation {
  /** bow_linear: exact word contributions; tfidf / transformer / distilbert: the model's own tokenization only. */
  kind?: "bow_linear" | "tfidf" | "transformer" | "distilbert";
  description?: string;
  normalized_text: string;
  tokens: string[];
  recognized_tokens: string[];
  unknown_tokens: string[];
  recognized_phrases?: string[];
  ngram_range?: number[];
  explained_class?: string;
  runner_up_class?: string;
  intercept?: number;
  class_score?: number;
  contributions: Contribution[];
  top_class_features: { feature: string; weight: number }[];
}

export interface Prediction extends Decision {
  model_id: string;
  model_name: string;
  input: string;
  class_order: string[];
  probabilities: Record<string, number>;
  ranked: { intent: string; probability: number }[];
  default_threshold: number;
  recognized_tokens: string[];
  unknown_tokens: string[];
  explanation: Explanation;
  inference_ms: number;
  workflow?: Workflow;
}

/** Illustrative Sole workflow (simulation only; nothing is executed). Mirrors demo/backend/workflow.py. */
export interface Workflow {
  kind: "route" | "confirm" | "clarify";
  screen: string | null;
  requires_confirmation: boolean;
  message: string;
  options: string[];
  entities: { amount: string | null; recipient: string | null; biller: string | null };
  steps: string[];
  note: string;
  missing?: string[];
  explicit_request?: boolean;
}

export interface ModelSummary {
  id: string;
  name: string;
  available: boolean;
  status: "available" | "coming_soon" | "error" | string;
  group?: "primary" | "history" | string;
  error?: string | null;
}

export interface ModelEvaluation {
  source: string;
  test_n: number | null;
  test_accuracy: number | null;
  test_macro_f1: number | null;
  test_weighted_f1: number | null;
  test_macro_precision: number | null;
  test_macro_recall: number | null;
  test_macro_roc_auc: number | null;
  test_log_loss: number | null;
  test_top2_accuracy: number | null;
  test_mean_confidence: number | null;
  test_macro_f1_ci95: [number, number] | null;
  validation_macro_f1: number | null;
  expected_calibration_error: number | null;
  known_intent_coverage_at_default: number | null;
  unknown_rejection_rate_at_default: number | null;
  median_latency_ms: number | null;
  p95_latency_ms?: number | null;
  validation_accuracy?: number | null;
  unknown_safe_fallback_at_default?: number | null;
  training_seconds: number | null;
  model_size_mb: number | null;
  n_parameters?: number | null;
}

export interface ModelInfo {
  id: string;
  name: string;
  group?: string;
  family: string;
  explainable?: boolean;
  original_author?: string | null;
  version: string | null;
  dataset_version?: string | null;
  trained_on?: string[] | null;
  model_file: string;
  model_sha256: string;
  details: { label: string; value: string }[];
  classes: string[];
  n_classes: number;
  unknown_label: string;
  unknown_label_is_model_class: boolean;
  default_threshold: number;
  default_threshold_source: string;
  fallback_rule: string;
  loaded?: boolean;
  evaluation: ModelEvaluation;
}

export interface CompareEntry {
  model_id: string;
  model_name: string;
  ok: boolean;
  error: string | null;
  prediction: Prediction | null;
}

/** One row of results/comparison/model_comparison.json (generated by python -m scripts.compare). */
export interface ComparisonRow {
  model: string;
  display_name: string;
  original_author: string;
  raw_test_accuracy: number;
  raw_test_correct: number;
  raw_test_n: number;
  test_macro_f1: number;
  test_weighted_f1: number;
  test_macro_roc_auc_ovr: number;
  default_threshold: number;
  known_coverage_at_default: number;
  overall_correct_routing_at_default: number;
  unknown_rejection_at_default: number;
  unknown_help_support_at_default: number;
  unknown_safe_fallback_at_default: number;
  unknown_to_financial_at_default: number;
  latency_p50_ms: number | null;
  latency_p95_ms: number | null;
  latency_device: string | null;
  model_size_mb: number;
  n_parameters: number | null;
  typo_test_accuracy: number;
}

export interface Comparison {
  generated_utc: string;
  source: string;
  models: ComparisonRow[];
  missing: string[];
}

export interface HistoryEntry {
  key: string;
  prediction: Prediction;
  thresholdUsed: number;
  finalIntentAtTime: string;
}

export interface SampleCategory {
  id: string;
  label: string;
  intent_hint: string | null;
  commands: string[];
}
